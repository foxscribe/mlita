/* 15.1. Игра в игре (5)
 * Вася и Петя любят игры со спичками. Несколько дней они играли в следующую игру. 
 * Два игрока поочередно забирают из кучки, содержащей N спичек, от 1 до M спичек. 
 * Выигрывает игрок, после хода которого кучка спичек опустеет. Доведя до 
 * совершенства свое мастерство, они решили изменить правила. Первый игрок задает 
 * значение N. Потом второй игрок указывает величину M. Далее игроки поочередно берут
 * спички, начиная с первого игрока. По жребию первым игроком оказался Вася. Для 
 * продления удовольствия Петя при любых дальнейших ответах Васи собирается выиграть
 * так, чтобы партия состояла из наибольшего числа ходов. Укажите правильный ответ Пети.
 * Гаврилов Я. К.
 * Среда: Debian GNU/Linux 14, g++ 14.2.0; -std=c++23
 */

#include <iostream>
#include <fstream>

int main() 
{
    std::ifstream input("input.txt");
    std::ofstream output("output.txt");

    long long N;
    if (!(input >> N)) 
    { 
        goto exit;
    }

{
    long long ans = 0;

    if (N == 2) 
    {
        ans = 0;
    } 
    else 
    {
        long long min_div = N; 
        
        if (N % 3 == 0) 
        {
            min_div = 3;
        }
        else if (N % 4 == 0) 
        {
            min_div = 4;
        }
        else 
        {
            for (long long i = 5; i * i <= N; i += 2) 
            {
                if (N % i == 0) 
                {
                    min_div = i;
                    break;
                }
            }
        }
        
        if (N % 2 == 0 && min_div == N) 
        {
            min_div = N / 2;
        }
        
        ans = min_div - 1;
    }
    
    output << ans << '\n';
}

exit:
    input.close();
    output.close();
    return 0;
}